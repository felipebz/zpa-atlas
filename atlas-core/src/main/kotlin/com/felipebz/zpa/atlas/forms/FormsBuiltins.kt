    /** The types of the object ids the `FIND_` built-ins return, and of OLE values. */
    private val TYPES = hashSetOf(
        "ALERT", "BLOCK", "CANVAS", "EDITOR", "FORMMODULE", "GROUPCOLUMN", "ITEM", "LOV", "MENUITEM", "OLEOBJ", "OLEVAR",
        "PARAMLIST", "RECORDGROUP", "RELATION", "REPORT_OBJECT", "TAB_PAGE", "TIMER", "VIEWPORT", "VISUALATTRIBUTE", "WINDOW"
    )

    /** Whether the name written as [segments] is a built-in subprogram or exception, or a member of a built-in package. */
    fun isBuiltIn(segments: List<String>): Boolean = when (segments.size) {
        1 -> normalized(segments[0]) in SUBPROGRAMS
        2 -> normalized(segments[0]) in PACKAGES
        else -> false
    }

    /** Whether the type written as [segments] is a built-in type or a type of a built-in package (`TEXT_IO.FILE_TYPE`). */
    fun isBuiltInType(segments: List<String>): Boolean = when (segments.size) {
        1 -> normalized(segments[0]) in TYPES
        2 -> normalized(segments[0]) in PACKAGES
        else -> false
    }

    private fun normalized(name: String) = name.removeSurrounding("\"").uppercase(Locale.ROOT)
